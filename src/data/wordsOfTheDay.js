/**
 * Requirement 3:
 * Implement a daily rotating word feature strictly based on the current calendar date.
 * Deterministically computes index from current calendar year, month, and day.
 */
export function getWordOfTheDay(date = new Date()) {
  const year = date.getFullYear();
  const month = date.getMonth(); // 0-11
  const day = date.getDate(); // 1-31

  // Deterministic seed based on calendar date
  const dateSeed = year * 372 + (month + 1) * 31 + day;
  const index = Math.abs(dateSeed) % WORDS_OF_THE_DAY.length;

  const wordItem = WORDS_OF_THE_DAY[index];

  // Format today's human-readable date
  const formattedDate = date.toLocaleDateString('en-US', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric'
  });

  return {
    ...wordItem,
    date: "Daily Word",
    formattedDate,
    calendarDate: `${year}-${String(month + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`
  };
}
